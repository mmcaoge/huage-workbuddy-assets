def classify(title):
    """返回 (档位, 命中词) 或 (None, None)。"""
    if not title or not ANN_RE.search(title):
        return None, None
    for p in EXCL_PATTERNS:
        if re.search(p, title):
            return None, None
    for p in CORE_PATTERNS:
        m = re.search(p, title)
        if m:
            return 'core', m.group(0)
    return None, None


# 地区解析：从站点名/标题抽取市县
CITY_LIST = ['海口', '三亚', '三沙', '儋州', '五指山', '琼海', '文昌', '万宁', '东方',
             '定安', '屯昌', '澄迈', '临高', '白沙', '昌江', '乐东', '陵水', '保亭', '琼中']


def city_of(site, title):
    blob = (site or '') + ' ' + (title or '')
    for c in CITY_LIST:
        if c in blob:
            return c + '市' if c in ('海口', '三亚', '三沙', '儋州', '五指山', '琼海', '文昌', '万宁', '东方') else c + '县'
    if any(k in blob for k in ('省本级', '省厅', '海南省', '自由贸易港', '阳光海南')):
        return '省级'
    return ''


def main():
    rows, seen = [], set()
    # RAW 支持逗号分隔多来源（站群 SSI + 站群外独立县市），合并去重后统一过滤
    for path in [p.strip() for p in RAW.split(',') if p.strip()]:
        with open(path, encoding='utf-8') as f:
            for line in f:
                try:
                    r = json.loads(line)
                except Exception:
                    continue
                url = r.get('url') or ''
                if not url or url in seen:
                    continue
                seen.add(url)
                lvl, hit = classify(r.get('title'))
                if not lvl:
                    continue
                r['level'] = lvl
                r['hit'] = hit
                # groupname 是采集器写入的所属市县，与 site 一起参与识别
                # （海口等站点的 site 常是媒体名如「海口晚报」，需要 groupname 兜底）
                r['city'] = city_of('%s %s' % (r.get('site') or '', r.get('groupname') or ''),
                                    r.get('title'))
                rows.append(r)

    rows.sort(key=lambda r: (r['level'] != 'core', r.get('pub_date') or ''), reverse=False)
    rows.sort(key=lambda r: (r.get('pub_date') or ''), reverse=True)

    with open(OUT, 'w', encoding='utf-8') as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + '\n')

    core = [r for r in rows]
    print('原始 %d 条 → 社会调查类 %d 条' % (len(seen), len(rows)))
    print('\n=== 按站点 ===')
    for k, v in collections.Counter(r['site'] for r in rows).most_common():
        print('   %-22s %d' % (k, v))
    print('\n=== 按地区 ===')
    for k, v in collections.Counter(r['city'] for r in rows).most_common():
        print('   %-10s %d' % (k or '(未识别)', v))
    print('\n=== 按年份 ===')
    for k, v in sorted(collections.Counter((r.get('pub_date') or '')[:4] for r in rows).items()):
        print('   %s  %d' % (k, v))
    print('\n=== 按命中特征 ===')
    for k, v in collections.Counter(r['hit'] for r in rows).most_common(20):
        print('   %-14s %d' % (k, v))
    print('\n=== 样例（最新 30 条）===')
    for r in core[:30]:
        print('   %s | %-6s | %-46s | %s' % (r.get('pub_date'), r.get('city') or '-', (r.get('title') or '')[:46], (r.get('site') or '')[:12]))
    print('\n输出：%s' % OUT)


if __name__ == '__main__':
    main()
